# Calculates total purchase cost for a business
# ============================================

# Step i & ii: Create variables and assign values
business_name = "QuickMart Enterprises"  # Name of the business
product_name = "Laptop"                  # Product being purchased
product_price = 55000.0                  # Price of one unit
quantity_purchased = 3                   # Number of units bought

# Step iii: Calculate total purchase cost
total_cost = product_price * quantity_purchased

# Step iv: Display the purchase summary
print("===== PURCHASE SUMMARY =====")
print(f"Business Name: {business_name}")
print(f"Product Name: {product_name}")
print(f"Quantity Purchased: {quantity_purchased}")
print(f"Product Price: {product_price}")
print(f"Total Cost: {total_cost}")


# v) Difference between Interactive and Script mode:
# Interactive mode: you type one command at a time in the
# Python shell and see the result immediately, but the work
# is lost when you close the window.
# Script mode: you write all the code in a .py file and run
# the whole file; the code is saved permanently and reusable.
#
# vi) Which mode for a student management application?
# Script mode, because a complete application has many lines
# of code that must be saved and run repeatedly. Interactive
# mode loses everything when the session closes.
